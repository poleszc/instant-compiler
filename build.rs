use std::{
    env, fs,
    io::{self, Write},
    path::Path,
};

fn main() {
    lalrpop::process_root().unwrap();
    generate_parsing_tests().unwrap();
    generate_errors_tests().unwrap();
}

/// Builds the parsing test file before compilation.
fn generate_parsing_tests() -> io::Result<()> {
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR env variable doesn't exist");
    let destination = Path::new(&out_dir).join("generated_parsing_tests.rs");
    let mut file = fs::File::create(&destination)?;
    let test_dir = Path::new("tests").join("in");

    writeln!(&mut file, "/* AUTOGENERATED FILE */\n")?;

    for entry in fs::read_dir(test_dir)? {
        let entry = entry?;
        let path = entry.path();

        if path.is_file() && path.extension().and_then(|s| s.to_str()) == Some("ins") {
            let file_name = path.file_stem().unwrap().to_str().unwrap();
            let test_name = file_name.replace(|c: char| !c.is_alphanumeric(), "_");

            if file_name.starts_with("bad_") {
                writeln!(
                    &mut file,
                    "#[test]\nfn test_fail_{}() {{\n    assert_parsing_fails(r\"{}\");\n}}\n",
                    test_name,
                    path.display(),
                )?;
            } else {
                writeln!(
                    &mut file,
                    "#[test]\nfn test_pass_{}() {{\n    assert_parsing_succeeds(r\"{}\");\n}}\n",
                    test_name,
                    path.display(),
                )?;
            }
        }
    }
    println!("cargo:rerun-if-changed=tests/in");
    Ok(())
}

